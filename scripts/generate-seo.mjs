#!/usr/bin/env node
/* ============================================================
   MIZANORA PLATFORM — auto SEO files
   Reads the seed content in assets/js/data.js and regenerates:
     • sitemap.xml  (pages + every blog article)
     • rss.xml      (latest 20 articles)
   Runs locally via `node scripts/generate-seo.mjs`
   and automatically in CI (.github/workflows/seo.yml).
   ============================================================ */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dataSrc = readFileSync(join(root, "assets/js/data.js"), "utf8");

/* Host-aware: every Search Console property only accepts sitemaps whose <loc>
   URLs live under that same prefix. So each deploy target generates its own:
     node scripts/generate-seo.mjs --site=https://mizanoraorg.web.app
   Default (and what gets committed) = canonical SITE_URL from data.js.        */
const argSite = (process.argv.find((a) => a.startsWith("--site=")) || "").split("=")[1];
const SITE = (argSite || process.env.SITE_URL ||
  (dataSrc.match(/SITE_URL:\s*"([^"]+)"/) || [, "https://muaaz-iqbal.github.io/MIZANORAORG"])[1]
).replace(/\/$/, "");
const SITE_NAME = (dataSrc.match(/SITE_NAME:\s*"([^"]+)"/) || [, "Mizanora Platform"])[1];
const OWNER = (dataSrc.match(/OWNER_NAME:\s*"([^"]+)"/) || [, "Muaaz Iqbal"])[1];
const today = new Date().toISOString().slice(0, 10);

const esc = (s = "") => String(s)
  .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
  .replace(/"/g, "&quot;").replace(/'/g, "&apos;");

/* ---------- pull the blogs array out of data.js ---------- */
function sliceArray(name) {
  const start = dataSrc.indexOf(`${name}: [`);
  if (start === -1) return "";
  let i = dataSrc.indexOf("[", start), depth = 0, inStr = null;
  for (let j = i; j < dataSrc.length; j++) {
    const c = dataSrc[j], prev = dataSrc[j - 1];
    if (inStr) {
      if (c === inStr && prev !== "\\") inStr = null;
      continue;
    }
    if (c === '"' || c === "'" || c === "`") { inStr = c; continue; }
    if (c === "[" || c === "{") depth++;
    if (c === "]" || c === "}") {
      depth--;
      if (depth === 0) return dataSrc.slice(i, j + 1);
    }
  }
  return "";
}

const blogsSrc = sliceArray("blogs");
const blogRe = /slug:\s*"([^"]+)"[\s\S]{0,600}?title:\s*"((?:[^"\\]|\\.)*)"[\s\S]{0,600}?date:\s*"([^"]*)"[\s\S]{0,900}?excerpt:\s*"((?:[^"\\]|\\.)*)"/g;

const blogs = [];
let m;
while ((m = blogRe.exec(blogsSrc))) {
  blogs.push({
    slug: m[1],
    title: JSON.parse(`"${m[2]}"`),
    date: m[3] || today,
    excerpt: JSON.parse(`"${m[4]}"`),
  });
}
blogs.sort((a, b) => String(b.date).localeCompare(String(a.date)));

/* ---------- sitemap ---------- */
const pages = [
  { loc: "/", priority: "1.0", changefreq: "daily" },
  { loc: "/projects.html", priority: "0.9", changefreq: "weekly" },
  { loc: "/blog.html", priority: "0.9", changefreq: "daily" },
  { loc: "/about.html", priority: "0.8", changefreq: "monthly" },
  { loc: "/team.html", priority: "0.6", changefreq: "monthly" },
];

const urls = pages.map(p => `  <url>
    <loc>${SITE}${p.loc}</loc>
    <lastmod>${today}</lastmod>
    <changefreq>${p.changefreq}</changefreq>
    <priority>${p.priority}</priority>
  </url>`).concat(blogs.map(b => `  <url>
    <loc>${SITE}/blog.html?slug=${encodeURIComponent(b.slug)}</loc>
    <lastmod>${b.date || today}</lastmod>
    <changefreq>monthly</changefreq>
    <priority>0.7</priority>
  </url>`));

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Auto-generated by scripts/generate-seo.mjs — do not edit by hand -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.join("\n")}
</urlset>
`;

/* ---------- rss ---------- */
const rssItems = blogs.slice(0, 20).map(b => `    <item>
      <title>${esc(b.title)}</title>
      <link>${SITE}/blog.html?slug=${encodeURIComponent(b.slug)}</link>
      <guid isPermaLink="false">${esc(b.slug)}</guid>
      <pubDate>${new Date(b.date || today).toUTCString()}</pubDate>
      <description>${esc(b.excerpt)}</description>
    </item>`).join("\n");

const rss = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Auto-generated by scripts/generate-seo.mjs -->
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">
  <channel>
    <title>${esc(SITE_NAME)} — Blog</title>
    <link>${SITE}/blog.html</link>
    <atom:link href="${SITE}/rss.xml" rel="self" type="application/rss+xml"/>
    <description>Mizanora Platform — ${esc(OWNER)} ke projects, blogs aur updates.</description>
    <language>en-pk</language>
    <lastBuildDate>${new Date().toUTCString()}</lastBuildDate>
${rssItems}
  </channel>
</rss>
`;

/* ---------- robots.txt (host-aware sitemap line) ---------- */
const robots = `# Mizanora Platform — robots.txt
# ${SITE}/

User-agent: *
Allow: /
Disallow: /admin.html

# AI / LLM crawlers welcome (llms.txt dekhein)
User-agent: GPTBot
Allow: /

User-agent: ClaudeBot
Allow: /

User-agent: Google-Extended
Allow: /

User-agent: PerplexityBot
Allow: /

Sitemap: ${SITE}/sitemap.xml
`;

writeFileSync(join(root, "sitemap.xml"), sitemap);
writeFileSync(join(root, "rss.xml"), rss);
writeFileSync(join(root, "robots.txt"), robots);
console.log(`✅ sitemap.xml — ${pages.length} pages + ${blogs.length} articles  →  ${SITE}`);
console.log(`✅ rss.xml      — ${Math.min(blogs.length, 20)} items`);
console.log(`✅ robots.txt   — Sitemap: ${SITE}/sitemap.xml`);
